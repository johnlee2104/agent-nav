def test_check_flags_duplicate_rows(repo):
    lg.set_entry(repo, "a.txt", "purpose a", ["alpha"])
    p = lg.ledger_path(repo)
    p.write_text(p.read_text() * 2)  # what a union merge of two branches leaves
    assert lg.check(repo)["duplicate"] == ["a.txt"]
    assert lg.main(["--repo", repo, "update", "a.txt", "--keep"]) == 1  # ambiguous
    assert lg.main(["--repo", repo, "update", "a.txt", "-d", "merged"]) == 0
    assert lg.check(repo)["duplicate"] == []


def test_writers_keep_untouched_duplicate_rows_verbatim(repo2):
    # every writer used to round-trip through a by-path dict, so ANY write silently
    # collapsed an unrelated union-merge duplicate to its last row
    lg.set_entry(repo2, "a.txt", "purpose a", ["alpha"])
    (pathlib.Path(repo2) / "c.txt").write_text("c\n")
    lg.set_entry(repo2, "c.txt", "purpose c", ["gamma"])
    p = lg.ledger_path(repo2)
    b1 = '{"path":"b.txt","description":"side one","keywords":["one"],"sha":"x"}\n'
    b2 = '{"path":"b.txt","description":"side two","keywords":["two"],"sha":"y"}\n'
    lines = p.read_text().splitlines(keepends=True)
    p.write_text(lines[0] + b1 + b2 + lines[1])
    (pathlib.Path(repo2) / "a.txt").write_text("edited\n")

    def b_lines():
        return [ln for ln in p.read_text().splitlines(keepends=True) if '"b.txt"' in ln]

    assert lg.main(["--repo", repo2, "update", "a.txt", "--keep"]) == 0
    assert b_lines() == [b1, b2]
    assert lg.main(["--repo", repo2, "update", "a.txt", "-d", "new a"]) == 0
    assert b_lines() == [b1, b2]
    (pathlib.Path(repo2) / "c.txt").unlink()
    assert lg.main(["--repo", repo2, "update", "c.txt"]) == 0  # drop another path
    assert b_lines() == [b1, b2]
    assert lg.main(["--repo", repo2, "update", "b.txt", "-d", "merged"]) == 0
    assert [e["description"] for e in lg.load(repo2) if e["path"] == "b.txt"] == ["merged"]


def _stage_scratch_row(repo):
    lg.set_entry(repo, "a.txt", "purpose a", ["alpha"])
    (pathlib.Path(repo) / "scratch.txt").write_text("tmp\n")
    assert lg.main(["--repo", repo, "update", "scratch.txt", "-d", "scratch"]) == 0


def test_staged_check_flags_row_of_unadded_file(repo):
    _stage_scratch_row(repo)
    _git(repo, "add", LEDGER)
    assert lg.check(repo, staged=True)["orphaned"] == ["scratch.txt"]
    assert lg.main(["--repo", repo, "check", "--staged"]) == 1


def test_staged_orphan_read_from_index_not_worktree(repo):
    # drop the row in the worktree but leave the STAGED jsonl as is
    _stage_scratch_row(repo)
    _git(repo, "add", LEDGER)
    assert lg.main(["--repo", repo, "update", "scratch.txt"]) == 0
    assert "scratch.txt" in lg.check(repo, staged=True)["orphaned"]


def test_unstaged_orphan_row_does_not_block_commit(repo):
    # someone else's unstaged row for an un-added file is not this commit's business
    lg.set_entry(repo, "a.txt", "purpose a", ["alpha"])
    _git(repo, "add", LEDGER)
    (pathlib.Path(repo) / "scratch.txt").write_text("tmp\n")
    assert lg.main(["--repo", repo, "update", "scratch.txt", "-d", "scratch"]) == 0
    assert lg.check(repo, staged=True)["orphaned"] == []


def test_staged_orphan_includes_intent_to_add(repo):
    # `git add -N` puts the path in ls-files but not in the committed tree
    _stage_scratch_row(repo)
    _git(repo, "add", "-N", "scratch.txt")
    _git(repo, "add", LEDGER)
    assert "scratch.txt" in lg.check(repo, staged=True)["orphaned"]


# --------------------------------------------------------------------------- #
# the pre-commit hook really runs the ledger, from each worktree's own copy
# --------------------------------------------------------------------------- #
@pytest.fixture
def vendored(repo, monkeypatch):
    """`repo` with ledger.py vendored at tools/ledger.py, described and committed,
    and the hook installed the way a vendored user would (argv[0] = the copy)."""
    top = pathlib.Path(repo)
    (top / "tools").mkdir()
    shutil.copy(lg.__file__, top / "tools/ledger.py")
    _git(repo, "-c", "user.email=t@t.t", "-c", "user.name=t", "add", "tools/ledger.py")
    lg.ingest(repo, [{"path": "a.txt", "description": "greeting", "keywords": ["a"]},
                     {"path": "tools/ledger.py", "description": "vendored ledger",
                      "keywords": ["ledger"]}])
    _git(repo, "add", LEDGER)
    _git(repo, "-c", "user.email=t@t.t", "-c", "user.name=t", "commit", "-qm", "init")
    monkeypatch.setattr(sys, "argv", [str(top / "tools/ledger.py")])
    assert lg.install_hook(repo) == 0
    return repo


def _commit(repo, msg):
    return subprocess.run(["git", "-C", repo, "-c", "user.email=t@t.t",
                           "-c", "user.name=t", "commit", "-qm", msg],
                          capture_output=True, text=True)


def test_vendored_hook_uses_repo_relative_guarded_path(vendored):
    hook = (pathlib.Path(vendored) / ".git/hooks/pre-commit").read_text()
    assert "python3 tools/ledger.py check --staged" in hook
    assert "[ -f tools/ledger.py ]" in hook
    assert str(vendored) not in hook  # no absolute path baked in


def test_vendored_hook_blocks_stale_then_passes(vendored):
    (pathlib.Path(vendored) / "a.txt").write_text("changed\n")
    _git(vendored, "add", "a.txt")
    r = _commit(vendored, "should block")
    assert r.returncode != 0
    out = r.stdout + r.stderr  # git routes hook output to stderr
    assert "stale" in out and "a.txt" in out  # blocked by the ledger itself
    assert lg.main(["--repo", vendored, "update", "a.txt", "--keep"]) == 0
    _git(vendored, "add", LEDGER)
    assert _commit(vendored, "now fresh").returncode == 0


def test_vendored_hook_skips_branch_without_the_tool(vendored):
    # the hooks dir is shared by every branch and worktree: one cut before the tool
    # was vendored must still commit instead of failing on a missing file
    _git(vendored, "rm", "-q", "tools/ledger.py")
    assert lg.main(["--repo", vendored, "update", "tools/ledger.py"]) == 0
    _git(vendored, "add", LEDGER)
    assert _commit(vendored, "drop the tool").returncode == 0
    (pathlib.Path(vendored) / "a.txt").write_text("changed, no ledger update\n")
    _git(vendored, "add", "a.txt")
    assert _commit(vendored, "no tool, no gate").returncode == 0
