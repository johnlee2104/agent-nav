def test_keep_refreshes_sha_and_keeps_fields(repo2):
    lg.set_entry(repo2, "a.txt", "purpose a", ["alpha"], status="draft")
    lg.set_entry(repo2, "b.txt", "purpose b", ["beta"])
    for n in ("a.txt", "b.txt"):
        (pathlib.Path(repo2) / n).write_text("edited\n")
    assert lg.main(["--repo", repo2, "update", "a.txt", _abs(repo2, "b.txt"), "--keep"]) == 0
    rows = _rows(repo2)
    assert rows["a.txt"]["description"] == "purpose a"
    assert rows["a.txt"]["keywords"] == ["alpha"] and rows["a.txt"]["status"] == "draft"
    assert rows["b.txt"]["description"] == "purpose b"
    assert lg.check(repo2)["stale"] == []


def test_keep_refuses_rowless_path_and_writes_nothing(repo2, capsys):
    lg.set_entry(repo2, "a.txt", "purpose a", ["alpha"])
    (pathlib.Path(repo2) / "a.txt").write_text("edited\n")
    before = lg.ledger_path(repo2).read_bytes()
    assert lg.main(["--repo", repo2, "update", "a.txt", "b.txt", "--keep"]) == 1
    err = capsys.readouterr().err
    assert "b.txt" in err and "-d" in err
    assert lg.ledger_path(repo2).read_bytes() == before
    with pytest.raises(SystemExit) as ex:
        lg.main(["--repo", repo2, "update", "a.txt", "--keep", "-d", "x"])
    assert ex.value.code == 2


