"""Regression tests for the refinements ported from a production fork of the ledger.

Each block pins a failure that happened in real agent use: silent field loss,
silent truncation, raw absolute paths matching nothing, union-merge duplicates
collapsing, and staged-check blind spots. No model, no network.
"""
import pathlib
import shutil
import subprocess
import sys

import pytest

from agent_nav import ledger as lg

LEDGER = lg.LEDGER_REL


def _git(repo, *args):
    subprocess.run(["git", "-C", str(repo), *args], check=True,
                   capture_output=True, text=True)


@pytest.fixture
def repo(tmp_path):
    """A git repo with one staged (never committed) text file, a.txt."""
    _git(tmp_path, "init", "-q")
    (tmp_path / "a.txt").write_text("hello\n")
    _git(tmp_path, "add", "a.txt")
    return str(tmp_path)


@pytest.fixture
def repo2(repo):
    """`repo` plus a second tracked file (b.txt) with no ledger row."""
    (pathlib.Path(repo) / "b.txt").write_text("world\n")
    _git(repo, "add", "b.txt")
    return repo


def _abs(repo, rel="a.txt"):
    return str(pathlib.Path(repo) / rel)


def _rows(repo):
    return {e["path"]: e for e in lg.load(repo)}


def _ignored(repo, name="ign.txt"):
    (pathlib.Path(repo) / ".gitignore").write_text(name + "\n")
    (pathlib.Path(repo) / name).write_text("ignored\n")
    return name


