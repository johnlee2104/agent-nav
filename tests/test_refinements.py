def _gen(path, text):
    return {"description": "generated", "keywords": ["gen"]}


def test_auto_refuses_described_row(repo, capsys):
    lg.set_entry(repo, "a.txt", "curated purpose", ["alpha"])
    assert lg.update(repo, ["a.txt"], describe_fn=_gen) == 1
    (entry,) = lg.load(repo)
    assert entry["description"] == "curated purpose"
    assert entry["keywords"] == ["alpha"]
    assert "a.txt" in capsys.readouterr().err


def test_auto_describes_undescribed_row(repo):
    assert lg.update(repo, ["a.txt"], describe_fn=_gen) == 0
    (entry,) = lg.load(repo)
    assert entry["description"] == "generated"


def test_auto_mixed_lands_undescribed_keeps_described(repo2):
    lg.set_entry(repo2, "a.txt", "curated purpose", ["alpha"])
    assert lg.update(repo2, ["a.txt", "b.txt"], describe_fn=_gen) == 1
    by_path = _rows(repo2)
    assert by_path["a.txt"]["description"] == "curated purpose"
    assert by_path["b.txt"]["description"] == "generated"


def test_redescribe_overwrites_and_prints_old_new(repo, capsys):
    lg.set_entry(repo, "a.txt", "curated purpose", ["alpha"])
    assert lg.update(repo, ["a.txt"], describe_fn=_gen, redescribe=True) == 0
    (entry,) = lg.load(repo)
    assert entry["description"] == "generated"
    err = capsys.readouterr().err
    assert "curated purpose" in err and "generated" in err


def test_redescribe_preserves_status(repo):
    # status is never generated by describe_fn — dropping it is pure loss
    lg.set_entry(repo, "a.txt", "curated purpose", ["alpha"], status="superseded")
    assert lg.update(repo, ["a.txt"], describe_fn=_gen, redescribe=True) == 0
    (entry,) = lg.load(repo)
    assert entry["description"] == "generated"
    assert entry["keywords"] == ["gen"]   # --auto does replace keywords
    assert entry["status"] == "superseded"


